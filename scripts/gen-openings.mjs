// Generates src/review/openings/openings.generated.ts from the Lichess
// `chess-openings` list (CC0 1.0, public domain).
//
//   npm run gen:openings                 fetch a.tsv..e.tsv at the pinned commit
//   npm run gen:openings -- --dir <path> read them from a local checkout instead
//
// Every PGN is replayed with chess.js and every prefix position is added, not only
// the final one: many intermediate positions have no row of their own but are still
// book. A position key is the first three FEN fields (placement, side to move,
// castling). Named positions keep the first name found (files a..e in order).
// To keep the lazy chunk small, keys and names are sorted and front-coded and named
// positions point into a name table (format described in the generated header).
// Output is sorted so regenerating gives identical bytes. Not part of `prebuild`:
// the output is committed.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Chess } from 'chess.js'

const REPO = 'lichess-org/chess-openings'
const SHA = '3fd6ce992679e4d991a6bb4dade71f2b826c568a'
const FILES = ['a.tsv', 'b.tsv', 'c.tsv', 'd.tsv', 'e.tsv']
const MAX_BYTES = 500 * 1024

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src', 'review', 'openings', 'openings.generated.ts')

const dirFlag = process.argv.indexOf('--dir')
const localDir = dirFlag >= 0 ? process.argv[dirFlag + 1] : undefined

async function readTsv(file) {
  if (localDir) return readFileSync(join(localDir, file), 'utf8')
  const url = `https://raw.githubusercontent.com/${REPO}/${SHA}/${file}`
  const res = await fetch(url)
  if (!res.ok) throw new Error(`gen-openings: ${url} returned ${res.status}`)
  return res.text()
}

const positionKey = (fen) => fen.split(' ').slice(0, 3).join(' ')

/** key -> { eco, name } | null (null = book position without its own name). */
const book = new Map()
let rows = 0

for (const file of FILES) {
  const text = await readTsv(file)
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim()) continue
    const [eco, name, pgn] = line.split('\t')
    if (eco === 'eco') continue // header
    if (!/^[A-E]\d\d$/.test(eco) || !name || !pgn) throw new Error(`gen-openings: bad row in ${file}: ${line}`)
    rows++
    const chess = new Chess()
    const sans = pgn
      .replace(/\d+\.(\.\.)?/g, ' ')
      .split(/\s+/)
      .filter(Boolean)
    for (const [i, san] of sans.entries()) {
      chess.move(san) // throws on an illegal move, which would mean bad data
      const key = positionKey(chess.fen())
      const last = i === sans.length - 1
      if (last) {
        if (!book.get(key)) book.set(key, { eco, name })
      } else if (!book.has(key)) {
        book.set(key, null)
      }
    }
  }
}

/** Front coding: 2 base-36 digits for the length shared with the previous string, then the rest. */
function frontCode(strings) {
  let prev = ''
  return strings.map((s) => {
    let n = 0
    while (n < s.length && n < prev.length && n < 1295 && s[n] === prev[n]) n++
    prev = s
    return n.toString(36).padStart(2, '0') + s.slice(n)
  })
}

// Name table: unique `name\teco` strings, sorted so related names share prefixes.
const nameEntries = [...new Set([...book.values()].filter(Boolean).map((e) => `${e.name}\t${e.eco}`))].sort()
const nameIndex = new Map(nameEntries.map((entry, i) => [entry, i]))

// Positions: sorted keys, front-coded, plus `\t<base-36 name index>` when named.
const keys = [...book.keys()].sort()
const codedKeys = frontCode(keys)
const positions = keys.map((key, i) => {
  const entry = book.get(key)
  return entry ? `${codedKeys[i]}\t${nameIndex.get(`${entry.name}\t${entry.eco}`).toString(36)}` : codedKeys[i]
})

const named = keys.filter((k) => book.get(k)).length
const source = `https://github.com/${REPO}/tree/${SHA}`
const content = `// GENERATED by scripts/gen-openings.mjs. Do not edit by hand; run \`npm run gen:openings\`.
// Source: ${source} (a.tsv..e.tsv)
// Licence: CC0 1.0 Universal (public domain).
// ${rows} rows, ${keys.length} book positions (${named} named), ${nameEntries.length} distinct names.
// Format (decoded by ./book.ts):
// - Strings are front-coded: 2 base-36 digits giving the length shared with the previous
//   string, then the remaining characters.
// - OPENING_NAMES: one \`name\\teco\` per line, sorted.
// - OPENING_POSITIONS: one position key per line (FEN placement, side to move, castling),
//   sorted, followed by \`\\t<base-36 index into OPENING_NAMES>\` when the position is named.
export const OPENING_NAMES: string = ${JSON.stringify(frontCode(nameEntries).join('\n'))}
export const OPENING_POSITIONS: string = ${JSON.stringify(positions.join('\n'))}
`

const bytes = Buffer.byteLength(content)
if (bytes > MAX_BYTES) throw new Error(`gen-openings: output is ${bytes} bytes, over the ${MAX_BYTES} cap`)
writeFileSync(out, content)
console.log(
  `gen-openings: wrote ${keys.length} positions (${named} named, ${nameEntries.length} names) from ${rows} rows, ${bytes} bytes`,
)
